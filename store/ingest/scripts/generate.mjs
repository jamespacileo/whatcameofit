// Writes what the service is built from, out of the store's own SQL, which this script
// never changes, and holds the migrations to the store's schema:
//   src/sql.generated.mjs              the statements of merge.sql, preview.sql and
//                                      ingest.sql, and every field a statement reads
//
//   migrations/*.sql                   never written here: a migration that was applied is
//                                      not rewritten. Applied in order to an empty
//                                      database they must make every table, index, view
//                                      and trigger of store/schema.sql, as written there.
//                                      A change to the schema is a new migration.
//
//   node scripts/generate.mjs           write src/sql.generated.mjs
//   node scripts/generate.mjs --check   fail when it is stale, or the migrations and the
//                                      schema have parted
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { KINDS } from "../src/kinds.mjs";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
const read = (name) => readFileSync(here(`../../${name}`), "utf8");

// A file's statements: split at a line holding only `;`, comment lines dropped. The same
// reading as store/proof/proof.py.
export function statements(text) {
  return text.split("\n;\n")
    .map((chunk) => chunk.split("\n").filter((line) => line.trim() && !line.startsWith("--")).join("\n"))
    .filter(Boolean);
}

export function named(text) {
  const out = {};
  let name = null, lines = [];
  for (const line of text.split("\n")) {
    if (line.startsWith("-- name:")) { name = line.slice(8).trim(); lines = []; }
    else if (line.trim() === ";" && name) { out[name] = lines.join("\n"); name = null; }
    else if (name && !line.startsWith("--")) lines.push(line);
  }
  return out;
}

// The fields of a staged record's body, for each kind: every field read by a statement or
// a view that names the kind, or by a view such a statement reads through. A statement
// that names two kinds gives each the fields of both, so this errs towards taking a field.
export function fieldsOf(kinds, texts) {
  const strip = (text) => text.split("\n").filter((line) => !line.trimStart().startsWith("--")).join("\n");
  const parts = texts.flatMap((text) => strip(text).split(/;\s*\n/)).map((sql) => ({
    sql, view: /CREATE VIEW (\w+)/.exec(sql)?.[1],
    kinds: new Set(kinds.filter((kind) => sql.includes(`'${kind}'`))),
    fields: new Set([...sql.matchAll(/body\s*->>?\s*'([a-z_0-9]+)'/g)].map(([, field]) => field)),
  }));
  const views = parts.filter((part) => part.view);
  for (let grew = true; grew;) {
    grew = false;
    for (const part of parts) {
      for (const view of views) {
        if (view === part || !new RegExp(`\\b${view.view}\\b`).test(part.sql)) continue;
        for (const name of ["fields", "kinds"]) {
          for (const item of view[name]) if (!part[name].has(item)) { part[name].add(item); grew = true; }
        }
      }
    }
  }
  const of = Object.fromEntries(kinds.map((kind) => [kind, new Set()]));
  for (const part of parts) {
    // A view that names no kind reads a parent's key for whichever kind is read through it.
    for (const kind of part.kinds.size ? part.kinds : kinds) for (const field of part.fields) of[kind].add(field);
  }
  return Object.fromEntries(kinds.map((kind) => [kind, [...of[kind]].sort()]));
}

export function generated() {
  const schema = read("schema.sql"), merge = read("merge.sql"), preview = read("preview.sql"), ingest = read("ingest.sql");
  const sql = [
    "// Generated by scripts/generate.mjs from store/merge.sql, store/preview.sql, store/ingest.sql",
    "// and store/schema.sql. Do not edit: change the SQL and run `pnpm run generate`.",
    `export const MERGE = ${JSON.stringify(statements(merge), null, 1)};`,
    `export const PREVIEW = ${JSON.stringify(statements(preview), null, 1)};`,
    `export const INGEST = ${JSON.stringify(named(ingest), null, 1)};`,
    "// For each kind of record, the fields of its body that a statement or a view reads.",
    `export const FIELDS_OF = ${JSON.stringify(fieldsOf(KINDS, [schema, merge, preview]), null, 1)};`,
    "",
  ].join("\n");
  return { "../src/sql.generated.mjs": sql };
}

// Where the migrations, applied in order, do not make what store/schema.sql says: each
// object of the schema that is missing from them or defined otherwise. Compared as
// SQLite keeps a definition, less comments, spacing and the quotes a rename adds. The
// migrations may make more (the service's own tables); the schema may not.
export async function schemaDrift() {
  const { DatabaseSync } = await import("node:sqlite");
  const objects = (texts) => {
    const db = new DatabaseSync(":memory:");
    for (const text of texts) db.exec(text);
    const rows = db.prepare("SELECT type, name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'").all();
    db.close();
    const plain = (sql) => sql.split("\n").map((line) => line.replace(/--.*$/, "")).join(" ").replace(/"/g, "").replace(/\s+/g, " ").trim();
    return new Map(rows.map((row) => [`${row.type} ${row.name}`, plain(row.sql)]));
  };
  const names = readdirSync(here("../migrations")).filter((name) => name.endsWith(".sql")).sort();
  const made = objects(names.map((name) => readFileSync(here(`../migrations/${name}`), "utf8")));
  const drift = [];
  for (const [name, sql] of objects([read("schema.sql")])) {
    if (!made.has(name)) drift.push(`${name}: in store/schema.sql, made by no migration`);
    else if (made.get(name) !== sql) drift.push(`${name}: the migrations make it otherwise than store/schema.sql says`);
  }
  return drift;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  let stale = 0;
  for (const [path, text] of Object.entries(generated())) {
    if (process.argv.includes("--check")) {
      let have = null;
      try { have = readFileSync(here(path), "utf8"); } catch {}
      if (have !== text) { stale += 1; console.error(`${path} is not what the store's SQL gives: run \`pnpm run generate\``); }
    } else writeFileSync(here(path), text);
  }
  for (const line of await schemaDrift()) { stale += 1; console.error(`${line}: add a migration, never change one that was applied`); }
  process.exit(stale ? 1 : 0);
}
